export type PublishingDict = typeof PUBLISHING_TEXT.ko;

const currentLang = (): "ko" | "en" => (String(readStorage("nk_lang")).replace(/^"|"$/g, "") === "en" ? "en" : "ko");

export function usePublishingText(): PublishingDict {
  const [lang, setLang] = useState(currentLang);
  useEffect(() => {
    const sync = () => setLang(currentLang());
    const onStorage = (e: StorageEvent) => { if (e.key === "nk_lang" || e.key === null) sync(); };
    window.addEventListener("nk:lang-changed", sync);
    window.addEventListener("storage", onStorage);
    return () => { window.removeEventListener("nk:lang-changed", sync); window.removeEventListener("storage", onStorage); };
  }, []);
  return PUBLISHING_TEXT[lang] as PublishingDict;
}

/** 서버 오류 코드 → 사람 문구. */
export function apiErrorText(t: PublishingDict, e: unknown): string {
  const code = String((e as { code?: string })?.code || "");
  const message = String((e as { message?: string })?.message || "");
  return t.apiError[code] || (message && message !== code ? message : t.apiErrorFallback(code || "error"));
}

/** 시각 → '3분 전'. */
export function agoText(t: PublishingDict, iso: string, now = Date.now()): string {
  if (!iso) return t.pc.never;
  const min = Math.max(0, Math.round((now - Date.parse(iso)) / 60000));
  if (min < 1) return t.ago.now;
  if (min < 60) return t.ago.min(min);
  if (min < 48 * 60) return t.ago.hour(Math.round(min / 60));
  return t.ago.day(Math.round(min / 1440));
}
